      end)
    end
  end
})

-- ============================================================
--  SEEKBAR UPDATE LOOP
-- ============================================================
local updH = Handler(Looper.getMainLooper())
local updR
updR = Runnable{
  run = function()
    pcall(function()
      if currentFileType == "video" and videoView.isPlaying() then
        local cur, dur = videoView.getCurrentPosition(), videoView.getDuration()
        seekBar.setMax(dur); seekBar.setProgress(cur)
        timeCurrent.setText(formatDuration(cur)); timeTotal.setText(formatDuration(dur))
      elseif currentFileType == "audio" and mediaPlayer.isPlaying() then
        local cur, dur = mediaPlayer.getCurrentPosition(), mediaPlayer.getDuration()
        seekBar.setMax(dur); seekBar.setProgress(cur)
        timeCurrent.setText(formatDuration(cur)); timeTotal.setText(formatDuration(dur))
      end
    end)
    updH.postDelayed(updR, 1000)
  end
}
updH.postDelayed(updR, 1000)

