local function formatDuration(ms)
  if not ms or ms <= 0 then return "00:00" end
  local s = math.floor(ms / 1000)
  return string.format("%02d:%02d", math.floor(s/60), s % 60)
end

local function showSafeDialog(dialogOrBuilder)
  local dlg
  if dialogOrBuilder.create then dlg = dialogOrBuilder.create() else dlg = dialogOrBuilder end
  if not activity then
    pcall(function()
      local wt = WindowManager.LayoutParams.TYPE_SYSTEM_ALERT
      if Build.VERSION.SDK_INT >= 26 then wt = WindowManager.LayoutParams.TYPE_APPLICATION_OVERLAY end
      dlg.getWindow().setType(wt)
    end)
  end
  dlg.show()
  return dlg
end

local function getDisplayName(uri)
  local name = nil
  pcall(function()
    local cur = ctx.getContentResolver().query(uri, nil, nil, nil, nil)
    if cur then
      if cur.moveToFirst() then
        local idx = cur.getColumnIndex("_display_name")
        if idx >= 0 then name = cur.getString(idx) end
      end
      cur.close()
    end
  end)
  if not name or name == "" then name = "Selected File" end
  return name
end

