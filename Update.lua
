-- ============================================================
--  APPLY SPEED
-- ============================================================
local function applySpeed()
  if Build.VERSION.SDK_INT < 23 then return end
  pcall(function()
    local PP = luajava.bindClass("android.media.PlaybackParams")
    local mp
    if currentFileType == "video" and videoMediaPlayer then mp = videoMediaPlayer
    elseif currentFileType == "audio" then mp = mediaPlayer end
    if mp then
      local p = mp.getPlaybackParams()
      if not p then p = PP() end
      p.setSpeed(playbackSpeed)
      mp.setPlaybackParams(p)
    end
  end)
end

-- ============================================================
--  LOAD MEDIA  (auto-play on selection)
-- ============================================================
local function loadMediaFromUri(uri, mediaType)
  local displayName = getDisplayName(uri)

  -- stop whatever is currently playing
  pcall(function() if mediaPlayer.isPlaying() then mediaPlayer.stop() end end)
  pcall(function() mediaPlayer.reset() end)
  pcall(function() if videoView.isPlaying() then videoView.stopPlayback() end end)

  currentFileType = mediaType
  prefs.edit().putString("currentFileType", mediaType).apply()

  fileInfoView.setText((mediaType == "video" and "Video: " or "Audio: ") .. displayName)
  seekBarLayout.setVisibility(View.VISIBLE)
  controlRow.setVisibility(View.VISIBLE)
  speedRow.setVisibility(View.VISIBLE)
  btnPlayPause.setText("Play")
  timeCurrent.setText("00:00")
  timeTotal.setText("00:00")
  seekBar.setProgress(0)

  if mediaType == "video" then
    audioPlaceholder.setVisibility(View.GONE)
    videoFrame.setVisibility(View.VISIBLE)
    videoView.setVideoURI(uri)
    videoView.requestFocus()

    videoView.setOnPreparedListener(MediaPlayer.OnPreparedListener{
      onPrepared = function(mp)
        videoMediaPlayer = mp
        mp.setLooping(singleLoop)
        local dur = videoView.getDuration()
        if dur > 0 then
          seekBar.setMax(dur)
          timeTotal.setText(formatDuration(dur))
        end
        videoView.start()
        btnPlayPause.setText("Pause")
        applySpeed()
      end
    })
    videoView.setOnCompletionListener(MediaPlayer.OnCompletionListener{
      onCompletion = function(mp)
        if singleLoop then
          videoView.seekTo(0); videoView.start()
        else
          btnPlayPause.setText("Play")
        end
      end
    })
  else
    videoFrame.setVisibility(View.GONE)
    audioPlaceholder.setVisibility(View.VISIBLE)
    audioHint.setText("Playing: " .. displayName)

    pcall(function()
      mediaPlayer.reset()
      mediaPlayer.setDataSource(ctx, uri)
      mediaPlayer.setLooping(singleLoop)

      mediaPlayer.setOnPreparedListener(MediaPlayer.OnPreparedListener{
        onPrepared = function(mp)
          local dur = mp.getDuration()
          if dur > 0 then
            seekBar.setMax(dur)
            timeTotal.setText(formatDuration(dur))
          end
          mp.start()
          btnPlayPause.setText("Pause")
          applySpeed()
        end
      })

      mediaPlayer.setOnCompletionListener(MediaPlayer.OnCompletionListener{
        onCompletion = function(mp)
          if singleLoop then
            pcall(function() mp.seekTo(0); mp.start() end)
          else
            btnPlayPause.setText("Play")
          end
        end
      })

      mediaPlayer.prepareAsync()
    end)
  end
end
_G.loadMediaFromUri = loadMediaFromUri

-- ============================================================
--  FILE PICKER RESULT
-- ============================================================
function onActivityResult(reqCode, resCode, data)
  if reqCode == 1001 then
    if resCode == -1 and data then
      local uri = data.getData()
      if uri and _G.pendingSelectionType and _G.loadMediaFromUri then
        _G.loadMediaFromUri(uri, _G.pendingSelectionType)
      else
        Toast.makeText(_G.ctx or ctx, "Could not read selected file", Toast.LENGTH_SHORT).show()
      end
    end
    _G.pendingSelectionType = nil
  end
end

local function pickFile(mediaType)
  if not activity then
    Toast.makeText(ctx, "File picker requires an activity context", Toast.LENGTH_SHORT).show()
    return
  end
  _G.pendingSelectionType = mediaType
  local intent = Intent(Intent.ACTION_GET_CONTENT)
  intent.setType(mediaType == "video" and "video/*" or "audio/*")
  intent.addCategory(Intent.CATEGORY_OPENABLE)
  intent.addFlags(Intent.FLAG_GRANT_READ_URI_PERMISSION)
  activity.startActivityForResult(intent, 1001)
end

